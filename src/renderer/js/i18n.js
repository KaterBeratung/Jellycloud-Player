const dictionaries = { de, en };
let locale = 'de';

/** 'de-DE' -> 'de'; unbekannte Sprachen fallen auf Englisch zurueck. */
export function setLocale(value) {
  const short = String(value || 'de').toLowerCase().slice(0, 2);
  locale = dictionaries[short] ? short : 'en';
  document.documentElement.lang = locale;
}

export const getLocale = () => locale;

export function t(key, vars) {
  let s = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export const _dictionaries = dictionaries;
